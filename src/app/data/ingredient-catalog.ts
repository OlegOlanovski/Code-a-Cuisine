const ingredientByNormalizedName = new Map(
  INGREDIENT_CATALOG.map((ingredient) => [normalizeIngredientName(ingredient), ingredient]),
);

/**
 * Returns the catalogue spelling for an ingredient name.
 *
 * Matching ignores letter case and repeated whitespace, but does not accept
 * arbitrary words that merely use English characters.
 */
export function findCatalogIngredient(value: string): string | null {
  return ingredientByNormalizedName.get(normalizeIngredientName(value)) ?? null;
}

function normalizeIngredientName(value: string): string {
  return value.trim().replace(/\s+/g, ' ').toLocaleLowerCase('en-US');
}
